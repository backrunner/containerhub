#!/usr/bin/env python3
"""Record locked third-party metadata without local paths or credentials."""
import argparse
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true', help='Fail if the inventory is outdated')
args = parser.parse_args()
metadata = json.loads(subprocess.check_output(
    ['cargo', 'metadata', '--locked', '--all-features', '--format-version', '1'],
    cwd=ROOT, text=True))
packages = sorted((p for p in metadata['packages'] if p['source']),
                  key=lambda p: (p['name'], p['version']))
lines = ['# Dependency license inventory', '',
         'Generated by `python3 scripts/dependency-licenses.py` from `Cargo.lock`.',
         'Includes all resolved platforms and features, including build/test dependencies.',
         'License expressions are upstream declarations; see [third-party notices](../THIRD_PARTY_NOTICES.md).',
         '', '| Package | Version | Declared license | Source archive |',
         '| --- | --- | --- | --- |']
for package in packages:
    name, version, license_id = (package[k] for k in ('name', 'version', 'license'))
    if not license_id or not package['source'].startswith('registry+'):
        raise SystemExit(f'Manual license/source review required: {name} {version}')
    source = f'https://crates.io/api/v1/crates/{name}/{version}/download'
    lines.append(f'| {name} | {version} | {license_id} | [source]({source}) |')
content = '\n'.join(lines) + '\n'
destination = ROOT / 'docs/DEPENDENCIES.md'
if args.check:
    if not destination.exists() or destination.read_text() != content:
        raise SystemExit('Dependency inventory is outdated; run scripts/dependency-licenses.py')
else:
    destination.write_text(content)
print(f'{len(packages)} third-party packages recorded')
