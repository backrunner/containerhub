#!/usr/bin/env python3
"""Generate the prototype color variables from the native app's shared tokens."""
import json
from pathlib import Path
root = Path(__file__).resolve().parent.parent
tokens = json.loads((root / 'packages/design-tokens/themes.json').read_text())
names = {'accent_surface': 'accent-soft', 'warning': 'warn'}
blocks = ['/* Generated by scripts/design-tokens.py; edit packages/design-tokens/themes.json. */']
for mode, colors in tokens.items():
    selector = ':root' if mode == 'light' else ':root[data-theme=dark]'
    blocks.append(selector + ' {\n' + '\n'.join(f'  --{names.get(name, name)}: #{color};' for name, color in colors.items()) + '\n}')
(root / '.agents/design/tokens.css').write_text('\n'.join(blocks) + '\n')
