import assert from 'node:assert/strict';
import { mkdtemp, rm, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { resolve, join } from 'node:path';
import { ContainerHub } from '../packages/node/index.mjs';

const root = await mkdtemp(join(tmpdir(), 'containerhub-node-'));
const options = { binary: resolve('target/debug/containerhub-bridge'), stateDirectory: root, mode: 'demo' };
let client;
try {
  client = await ContainerHub.connect(options);
  const snapshot = await client.snapshot(), environment = snapshot.environment;
  assert.equal(environment, 'demo');
  await assert.rejects(client.reconcile(999999), { kind: 'NotFound' });
  const diagnostics = await client.diagnostics();
  assert.equal(diagnostics.environment, environment);
  const capabilities = new Map(diagnostics.checks.map(check => [check.feature, check.available]));
  assert.equal(capabilities.size, diagnostics.checks.length, 'diagnostics must not repeat features');
  for (const feature of ['containers', 'images', 'logs', 'inspect_container', 'inspect_image', 'stats', 'lifecycle', 'pull_image', 'cancel_pull', 'create_container', 'advanced_create', 'rebuild_ports', 'delete_container', 'delete_image']) {
    assert.equal(capabilities.get(feature), true, `${feature} is required by this management journey`);
  }
  assert.equal(capabilities.get('stacks'), false, 'the demo environment does not implement stacks');
  assert.ok(snapshot.containers.every(c => c.label_names.includes('dev.containerhub.demo')));
  assert.deepEqual(snapshot.capabilities, { stacks: false, rebuild_ports: true, create_advanced: true, create_secrets: true, create_startup: true, create_and_start: true, inspect_container: true, cancel_pull: true, inspect_image: true, delete_image: true, pull_image: true, create_container: true, delete_container: true, stats: true });
  const image = 'example.invalid/containerhub-test:fixture';
  const progress = [];
  const pull = await client.execute({ kind: 'pull_image', environment, reference: image }, { onProgress: op => progress.push(op.progress) });
  assert.ok(progress.includes('verifying'));
  assert.equal((await client.cancel(pull.id)).state, 'Succeeded');
  assert.equal(pull.state, 'Succeeded');
  assert.equal(pull.receipt, null);
  assert.equal((await client.reconcile(pull.id)).state, 'Succeeded');
  assert.ok((await client.resources('Image')).some(item => item.name === image));
  const create = { kind: 'create_container', environment, spec: { name: 'sdk-fixture', image, cpus: 1, memory_mib: 256, options: { networks: ['default'], volumes: [{ name: 'database-data', destination: '/data', read_only: true }], user: '1000:1000', working_directory: '/app', read_only: true }, ports: [{ host: '127.0.0.1', host_port: 18080, container_port: 80, protocol: 'tcp' }] } };
  const [a, b] = await Promise.all([client.submit(create, { operationId: 100 }), client.submit(create, { operationId: 100 })]);
  assert.equal(a.id, b.id);
  const created = await client.wait(100);
  assert.equal(created.state, 'Succeeded');
  let key = created.result.value.key;
  const inspected = await client.inspectContainer(key);
  assert.equal(inspected.read_only, true);
  assert.equal(inspected.working_directory, '/app');
  assert.equal(inspected.user, '1000:1000');
  assert.deepEqual(inspected.container.networks, ['default']);
  await assert.rejects(client.inspectContainer({ ...key, incarnation: 'stale' }), { kind: 'Conflict' });
  await assert.rejects(client.cancel(100), { kind: 'Unsupported' });
  const imageDetails = await client.inspectImage(environment, image);
  assert.deepEqual(imageDetails.used_by, [key]);
  assert.equal(imageDetails.key.environment, environment);
  await assert.rejects(client.inspectImage('wrong-environment', image), { kind: 'Conflict' });
  assert.equal((await client.execute({ kind: 'delete_image', key: imageDetails.key })).state, 'Failed');
  assert.equal((await client.snapshot()).containers.filter(c => c.key.id === key.id).length, 1);
  await assert.rejects(client.submit({ ...create, spec: { ...create.spec, name: 'different' } }, { operationId: 100 }), { kind: 'Conflict' });
  await assert.rejects(client.submit({ ...create, spec: { ...create.spec, name: '--all' } }), { kind: 'InvalidData' });
  await assert.rejects(client.submit({ kind: 'pull_image', environment, reference: 'x;touch /tmp/unsafe' }), { kind: 'InvalidData' });
  const lifecycle = action => ({ kind: 'lifecycle', key, action });
  assert.equal((await client.execute(lifecycle('Start'))).state, 'Succeeded');
  assert.equal((await client.stats(key)).memory_bytes, 48 * 1024 * 1024);
  assert.ok((await client.logs(key)).lines.length > 0);
  const exported = await client.exportLogs(key, { query: 'warn' });
  assert.equal(exported.line_count, 1);
  assert.ok(exported.content.includes('WARN'));
  assert.ok(exported.content.includes('bounded tail'));
  assert.ok(!exported.file_name.includes('/'));
  await assert.rejects(client.exportLogs(key, { query: 'x'.repeat(4097) }), { kind: 'InvalidData' });
  const runningDelete = await client.execute({ kind: 'delete_container', key });
  assert.equal(runningDelete.state, 'Failed');
  const wrong = { ...key, incarnation: 'not-the-same-container' };
  assert.equal((await client.execute({ kind: 'delete_container', key: wrong })).state, 'Failed');
  const beforeRebuild = (await client.snapshot()).containers.find(c => c.key.id === key.id);
  const rebuild = { kind: 'rebuild_ports', key, expected_state: 'Running', expected: beforeRebuild.ports, ports: [{ host: '127.0.0.1', host_port: 18081, container_port: 80, protocol: 'tcp' }] };
  const rebuilt = await client.execute(rebuild);
  assert.equal(rebuilt.state, 'Succeeded');
  const previousKey = key; key = rebuilt.result.value.key;
  assert.notEqual(key.incarnation, previousKey.incarnation);
  assert.equal(rebuilt.result.value.state, 'Running');
  assert.equal((await client.inspectContainer(key)).read_only, true);
  assert.equal((await client.snapshot()).containers.filter(c => c.key.id === key.id).length, 1);
  assert.equal((await client.execute(rebuild)).state, 'Failed', 'stale rebuild cannot remove replacement');
  assert.equal((await client.snapshot()).containers.find(c => c.key.id === key.id).key.incarnation, key.incarnation);
  assert.equal((await client.execute(lifecycle('Stop'))).state, 'Succeeded');
  const deletion = { kind: 'delete_container', key };
  assert.equal((await client.execute(deletion, { operationId: 200 })).state, 'Succeeded');
  assert.ok(!(await client.snapshot()).containers.some(c => c.key.id === key.id));
  const unusedImage = await client.inspectImage(environment, image);
  assert.equal(unusedImage.used_by.length, 0);
  assert.equal((await client.execute({ kind: 'delete_image', key: { ...unusedImage.key, digest: 'sha256:' + 'f'.repeat(64) } })).state, 'Failed');
  const imageDeletion = { kind: 'delete_image', key: unusedImage.key };
  assert.equal((await client.execute(imageDeletion, { operationId: 300 })).state, 'Succeeded');
  await assert.rejects(client.inspectImage(environment, image), { kind: 'NotFound' });
  const history = JSON.parse(await readFile(join(root, 'demo', 'operations.json'), 'utf8'));
  assert.equal(history.find(op => op.id === 100).state, 'Succeeded');
  assert.equal(history.find(op => op.id === 200).state, 'Succeeded');
  await client.close();
  client = await ContainerHub.connect(options);
  assert.equal((await client.submit(imageDeletion, { operationId: 300 })).state, 'Succeeded');
  assert.equal((await client.submit(deletion, { operationId: 200 })).state, 'Succeeded');
  assert.equal((await client.submit(create, { operationId: 100 })).state, 'Succeeded');
  assert.ok(!(await client.snapshot()).containers.some(c => c.key.id === key.id), 'restart must not replay an accepted create');
  console.log('PASS: Node SDK advanced creation, redacted inspect, progress callback, terminal cancellation, management, image inspect/in-use/stale-digest/delete, bounded filtered log export, durable dedupe and restart without replay');
} finally { if (client) await client.close(); await rm(root, { recursive: true, force: true }); }
